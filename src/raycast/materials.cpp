std::string_view materialName(int id) {
    // One bound, compared unsigned, so a negative id is out of range too; every id inside it has its own name.
    const auto index = static_cast<unsigned int>(id);
    if (index >= kNames.size()) {
        return "unknown";
    }
    return kNames.at(index);
}

