"""The files `coney-tools orig index` writes: the index itself and its reports, as TSV and Markdown.

They hold addresses, names, Coney paths and research links only (LEGAL.md's reference data), and go to a folder the
caller names, usually the scratch folder: the index changes with every pull request that touches `src/`, so it is
regenerated when needed rather than committed.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field

from coney_tools.orig_ghidra import PROBLEMS, Callee, GhidraFinding
from coney_tools.orig_index import Index, IndexRow, ResearchReport, SectionGap


@dataclass
class IndexResult:
    """Everything `orig index` found."""

    index: Index
    research: ResearchReport
    findings: list[GhidraFinding] = field(default_factory=list)
    callees: list[Callee] = field(default_factory=list)
    callee_subsystems: dict[int, str] = field(default_factory=dict)
    ghidra_source: str = "none"  # "live <url>", "listing <file>" or "none"


def render_index_tsv(rows: list[IndexRow]) -> str:
    """One line per tag: address, original name and file, Coney function, where, placement, research links."""
    lines = ["address\toriginal_name\toriginal_file\tconey_function\twhere\tplacement\tresearch"]
    for r in rows:
        lines.append(
            f"0x{r.address:08x}\t{r.name}\t{r.file}\t{r.coney}\t{r.where}\t{r.placement}\t{' '.join(r.research)}"
        )
    return "\n".join(lines) + "\n"


def render_untagged_tsv(result: IndexResult) -> str:
    """One line per untagged gameplay function: where, the function, its kind and its length in lines."""
    lines = ["where\tconey_function\tkind\tlines"]
    lines += [f"{u.where}\t{u.coney}\t{u.kind}\t{u.lines}" for u in result.index.untagged]
    return "\n".join(lines) + "\n"


def render_callees_tsv(result: IndexResult) -> str:
    """One line per untagged callee of tagged functions: address, Ghidra's name, subsystem, callers."""
    lines = ["address\tghidra_name\tsubsystem\tcalled_by"]
    for c in result.callees:
        callers = ",".join(f"0x{a:08x}" for a in c.callers)
        lines.append(f"0x{c.address:08x}\t{c.name}\t{result.callee_subsystems.get(c.address, '')}\t{callers}")
    return "\n".join(lines) + "\n"


def summary_lines(result: IndexResult) -> list[str]:
    """The counts `orig index` prints and puts at the top of its report."""
    index, research = result.index, result.research
    unique = len({r.address for r in index.rows})
    kinds = Counter(u.kind for u in index.untagged)
    problems = Counter(f.problem for f in result.findings)
    lines = [
        f"tags: {len(index.rows):,} in {len({r.path for r in index.rows}):,} files ({index.files:,} read), "
        f"{unique:,} original functions, {len(index.malformed):,} malformed",
        f"gameplay functions: {index.in_scope:,} defined; {index.tagged:,} tagged, {index.marked:,} marked "
        f"@coney-only, {index.marked_legacy:,} marked by the older wording, {len(index.untagged):,} neither "
        f"({', '.join(f'{n:,} {k}' for k, n in sorted(kinds.items()))})",
        f"ghidra ({result.ghidra_source}): "
        + (", ".join(f"{problems[p]:,} {p}" for p in PROBLEMS) if result.ghidra_source != "none" else "not checked"),
    ]
    if result.ghidra_source.startswith("live"):
        lines.append(f"untagged callees of tagged functions (game code): {len(result.callees):,}")
    lines.append(
        f"research: {len(research.gaps):,} linked sections cite no address, {len(research.missing):,} links to a "
        f"missing page or section, {len(research.uncited):,} tags whose linked pages lack their address, "
        f"{len(research.unlinked):,} tags with no research link"
    )
    return lines


def _gap_lines(gaps: list[SectionGap]) -> list[str]:
    """A research gap list as Markdown bullets: the link, its heading and the tags that link it."""
    lines = []
    for gap in gaps:
        tags = ", ".join(f"`{t.name.split()[0] if t.name else ''}` 0x{t.address:08x} ({t.where})" for t in gap.tags[:6])
        more = f" and {len(gap.tags) - 6} more" if len(gap.tags) > 6 else ""
        lines.append(f"- `{gap.link}` {gap.heading}: {tags}{more}")
    return lines


def render_research_gaps(result: IndexResult) -> str:
    """The research sections an audit should give original addresses to, for the agents that edit those pages."""
    research = result.research
    lines = [
        "# Research references to add",
        "",
        "Generated by `coney-tools orig index`; not committed. Each item is a research section that tagged Coney code",
        "links: give the behaviour it describes the original's address and function name (evidence level beside it).",
        "",
        f"## Sections that cite no original address ({len(research.gaps)})",
        "",
        *_gap_lines(research.gaps),
        "",
        f"## Links to a page or section that does not exist ({len(research.missing)})",
        "",
        *_gap_lines(research.missing),
        "",
        f"## Tags whose linked pages never cite their address ({len(research.uncited)})",
        "",
    ]
    for row in research.uncited:
        lines.append(f"- 0x{row.address:08x} `{row.name}` ({row.where}, {row.coney}): {' '.join(row.research)}")
    lines += ["", f"## Tags with no research link at all ({len(research.unlinked)})", ""]
    for row in research.unlinked:
        lines.append(f"- 0x{row.address:08x} `{row.name}` ({row.where}, {row.coney})")
    return "\n".join(lines) + "\n"


def render_report(result: IndexResult) -> str:
    """The index's report: the counts, the tags Ghidra does not bear out and the most-called untagged callees."""
    lines = ["# @orig index report", "", "Generated by `coney-tools orig index`; not committed.", ""]
    lines += [f"- {line}" for line in summary_lines(result)]
    if result.index.malformed:
        lines += ["", "## Malformed tags (not `@orig 0x<address> <Name> (<File>.cpp)`)", ""]
        lines += [f"- {m.where}: `{m.text}`" for m in result.index.malformed]
    lines += ["", "## Tags Ghidra does not bear out", ""]
    lines += ["| Problem | Address | Tag name | Ghidra name | Coney |", "| --- | --- | --- | --- | --- |"]
    order = {p: i for i, p in enumerate(PROBLEMS)}
    for f in sorted(result.findings, key=lambda f: (order[f.problem], f.row.address)):
        inside = f" (in 0x{f.start:08x})" if f.start is not None else ""
        lines.append(
            f"| {f.problem} | 0x{f.row.address:08x} | {f.row.name} | {f.ghidra_name}{inside} | "
            f"{f.row.coney} ({f.row.where}) |"
        )
    if result.callees:
        lines += ["", "## Untagged original functions that tagged ones call (first 200)", ""]
        lines += ["| Address | Ghidra name | Subsystem | Tagged callers |", "| --- | --- | --- | ---: |"]
        for c in result.callees[:200]:
            subsystem = result.callee_subsystems.get(c.address, "")
            lines.append(f"| 0x{c.address:08x} | {c.name} | {subsystem} | {len(c.callers)} |")
    return "\n".join(lines) + "\n"
