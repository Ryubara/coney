"""Rendering research/pcsx2-recipes.toml into the recipe pages, and `recipe show`'s plain text.

The pages are generated: an index, docs/guides/pcsx2-recipes.md (the intro and every recipe with its summary), and one
page per recipe group in docs/guides/pcsx2-recipes/ (each recipe's full section), so no page grows past the length a
guide may have (docs_check.LENGTH_WARNING). `coney-tools pcsx2 recipe render` rewrites them, removes a group page no
group makes any more, and `--check` fails when any is out of date.

Research: docs/guides/pcsx2-recipes.md
"""

from __future__ import annotations

import re
import sys
import textwrap
from pathlib import Path
from typing import Any

from coney_tools import recipes
from coney_tools.config import find_repo_root

PAGE = Path("docs/guides/pcsx2-recipes.md")  # the index
PAGES_DIR = Path("docs/guides/pcsx2-recipes")  # one page per group, named by `group_slug`
STATES_PAGE = "pcsx2-states.md"
UP = "../"  # from a group page to docs/guides/
WIDTH = 120  # the docs' line length (.markdownlint.yaml, MD013)
GENERATED = "<!-- Generated by `coney-tools pcsx2 recipe render` from research/pcsx2-recipes.toml. Do not edit. -->"
EVIDENCE_LABELS = {
    "confirmed-code": "confirmed (code)",
    "confirmed-runtime": "confirmed (runtime)",
    "inferred": "inferred",
    "speculative": "speculative",
}


def _wrap(text: str, indent: str = "") -> list[str]:
    """`text` as lines of at most WIDTH characters; blank-line-separated paragraphs stay separate, and a paragraph
    whose lines start with `- ` stays a list (each item wrapped on its own)."""
    lines: list[str] = []
    for number, paragraph in enumerate(text.strip().split("\n\n")):
        if number:
            lines.append("")
        rows = paragraph.splitlines()
        if rows and all(row.lstrip().startswith("- ") or row.startswith("  ") for row in rows):
            items: list[str] = []
            for row in rows:
                if row.lstrip().startswith("- "):
                    items.append(row.strip()[2:])
                else:
                    items[-1] += " " + row.strip()
            for item in items:
                lines += _fill(item, indent + "- ", indent + "  ")
        else:
            lines += _fill(paragraph, indent, indent)
    return lines


def _fill(text: str, first: str, rest: str) -> list[str]:
    """One paragraph filled to WIDTH, never breaking a word or a link."""
    return textwrap.wrap(
        " ".join(text.split()),
        WIDTH,
        initial_indent=first,
        subsequent_indent=rest,
        break_long_words=False,
        break_on_hyphens=False,
    )


def link(page: str, up: str = "") -> str:
    """A `docs/...` path as a link from docs/guides/, or from a page `up` ("../") folders below it."""
    target = page.removeprefix("docs/")
    if target.startswith("guides/"):
        return up + target.removeprefix("guides/")
    return up + "../" + target


#: A Markdown link's target that is a path: not an anchor of the page, a URL or an absolute path.
_RELATIVE_TARGET = re.compile(r"\]\((?![#/]|[A-Za-z][A-Za-z0-9+.-]*:)([^)\s]+)\)")


def _relink(text: str, up: str) -> str:
    """`text` written for docs/guides/ with every relative link prefixed by `up` ("../" for a page one folder down)."""
    return _RELATIVE_TARGET.sub(lambda found: f"]({up}{found[1]})", text) if up else text


def group_slug(group: str) -> str:
    """A group's page name: its lower-case words joined by hyphens."""
    return re.sub(r"[^a-z0-9]+", "-", group.lower()).strip("-")


def _cell(text: str) -> str:
    """Text safe inside a table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def _step_text(step: dict[str, Any]) -> str:
    """One step as one line of TOML-like text."""
    parts = []
    for key, value in step.items():
        if isinstance(value, dict):
            inner = ", ".join(f'{k} = "{v}"' for k, v in value.items())
            parts.append(f"{key} = {{ {inner} }}")
        elif isinstance(value, str):
            parts.append(f'{key} = "{value}"')
        elif isinstance(value, bool):
            parts.append(f"{key} = {'true' if value else 'false'}")
        elif isinstance(value, list):
            parts.append(f"{key} = [{', '.join(repr(v).replace(chr(39), chr(34)) for v in value)}]")
        else:
            parts.append(f"{key} = {value}")
    return "{ " + ", ".join(parts) + " }"


def _command(recipe: recipes.Recipe) -> str:
    """The command line that runs the recipe, with each parameter's default or a placeholder."""
    args = []
    for param in recipe.params:
        value = param.default if param.default not in (None, "") else f"<{param.name}>"
        args.append(f"--arg {param.name}={value}")
    tail = (" " + " ".join(args)) if args else ""
    return f"uv run --project python coney-tools pcsx2 recipe run {recipe.name} --copy COPY --agent ID{tail}"


def _preconditions(recipe: recipes.Recipe, up: str = "") -> str:
    """The patches and emulation state a run needs, as one cell; `up` is as in `link`."""
    emulation = {"running": "emulation running", "paused": "emulation paused", "either": "running or paused"}
    patches = ", ".join(f"`{p}`" for p in recipe.patches) or "none"
    text = f"patches: {patches}; {emulation[recipe.emulation]}"
    if recipe.state:
        text += f"; start state: `{recipe.state}` ([state library]({up}{STATES_PAGE}))"
    return text


def recipe_section(recipe: recipes.Recipe, up: str = "") -> list[str]:
    """One recipe's section of its group page; `up` ("../") is the way from that page to docs/guides/."""
    out = [f"## {recipe.name} {{#{recipe.name}}}", ""]
    out += _wrap(_relink(recipe.summary, up))
    out.append("")
    out += _wrap(_relink(recipe.how, up))
    out.append("")
    confirmed = recipe.confirmed
    seen = f"{confirmed.date}, copy `{confirmed.copy}`, PCSX2 {confirmed.pcsx2}, {confirmed.state}"
    if confirmed.note:
        seen += f"; {_relink(confirmed.note, up)}"
    params = "; ".join(
        f"`{p.name}` ({p.kind}{', default `' + p.default + '`' if p.default not in (None, '') else ''}): "
        + _relink(p.help, up)
        for p in recipe.params
    )
    research = ", ".join(f"[{r.removeprefix('docs/')}]({link(r, up)})" for r in recipe.research)
    out += [
        "| | |",
        "| --- | --- |",
        f"| Parameters | {_cell(params) or 'none'} |",
        f"| Preconditions | {_cell(_preconditions(recipe, up))} |",
        f"| Evidence | {EVIDENCE_LABELS[recipe.evidence]} |",
        f"| Ghidra | {_cell(', '.join(f'`{g}`' for g in recipe.ghidra))} |",
        f"| Research | {research} |",
        f"| Confirmed at runtime | {_cell(seen)} |",
        "",
    ]
    if recipe.steps:
        out += ["```sh", _command(recipe), "```", "", "Steps:", "", "```text"]
        out += [_step_text(step) for step in recipe.steps]
        out += ["```", ""]
    if recipe.example:
        out += ["```sh", *recipe.example.strip().splitlines(), "```", ""]
    return out


def _members(book: recipes.RecipeBook) -> dict[str, list[recipes.Recipe]]:
    """The recipes of each group that has any, in the order of the groups; the key is the group's name."""
    found = {group: [r for r in book.recipes.values() if r.group == group] for group in book.groups}
    return {group: members for group, members in found.items() if members}


def _group_page(group: str, members: list[recipes.Recipe]) -> str:
    """One group's page: its recipes listed, then the full section of each."""
    out = [f"# {group}", "", GENERATED, ""]
    out += _fill(f"One group of the [PCSX2 recipes](../{PAGE.name}): how to run a recipe is on that page.", "", "")
    out.append("")
    for r in members:
        out += _fill(f"[{r.name}](#{r.name}): {_relink(r.summary, UP)}", "- ", "  ")
    out.append("")
    for recipe in members:
        out += recipe_section(recipe, UP)
    while out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


def _index(book: recipes.RecipeBook, members: dict[str, list[recipes.Recipe]]) -> str:
    """The index page: the intro, then each group's recipes with their summaries, linked to the group's page.

    Each recipe's link carries the recipe's anchor too (an attribute list on the link), so a link to
    `pcsx2-recipes.md#name`, written before the pages were split, still lands on the recipe, a click from its page."""
    out = ["# PCSX2 recipes", "", GENERATED, ""]
    out += _wrap(book.intro)
    out.append("")
    for group, recipes_of_group in members.items():
        page = f"{PAGES_DIR.name}/{group_slug(group)}.md"
        out += [f"## {group}", ""]
        for r in recipes_of_group:
            out += _fill(f"[{r.name}]({page}#{r.name}){{#{r.name}}}: {r.summary}", "- ", "  ")
        out.append("")
    while out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


def render(book: recipes.RecipeBook) -> dict[str, str]:
    """Every page by path from the repository root: the index, then one page per group that has recipes."""
    members = _members(book)
    pages = {PAGE.as_posix(): _index(book, members)}
    for group, recipes_of_group in members.items():
        path = (PAGES_DIR / f"{group_slug(group)}.md").as_posix()
        if path in pages:
            raise recipes.RecipeError(f"groups {group!r} and another make the same page, {path}")
        pages[path] = _group_page(group, recipes_of_group)
    return pages


def recipe_text(recipe: recipes.Recipe) -> list[str]:
    """`recipe show`'s text: the section without the Markdown table."""
    out = [f"{recipe.name}: {recipe.summary}", ""]
    out += textwrap.wrap(" ".join(recipe.how.split()), 100)
    out.append("")
    for param in recipe.params:
        default = f" (default {param.default!r})" if param.default is not None else " (required)"
        out.append(f"  --arg {param.name}=...  {param.kind}{default}: {param.help}")
    out.append(f"preconditions: {_preconditions(recipe)}")
    out.append(f"evidence: {EVIDENCE_LABELS[recipe.evidence]}; ghidra: {', '.join(recipe.ghidra)}")
    out.append(f"research: {', '.join(recipe.research)}")
    c = recipe.confirmed
    out.append(f"confirmed at runtime: {c.date} on {c.copy}, PCSX2 {c.pcsx2}, {c.state}")
    if recipe.steps:
        out += ["", "steps:", *(f"  {_step_text(step)}" for step in recipe.steps), "", _command(recipe)]
    if recipe.example:
        out += ["", recipe.example.strip()]
    return out


def run_render(check_only: bool) -> int:
    """Write the pages (removing a group page no group makes), or with `check_only` report the stale ones, return 1."""
    root = find_repo_root(Path.cwd())
    wanted = render(recipes.load(root))
    stale = [path.relative_to(root).as_posix() for path in sorted((root / PAGES_DIR).glob("*.md"))]
    stale = [name for name in stale if name not in wanted]
    removed = list(stale)
    if not check_only:
        for name in removed:
            (root / name).unlink()
    for name, text in wanted.items():
        path = root / name
        current = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.is_file() else None
        if current != text:
            stale.append(name)
            if not check_only:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(text.encode("utf-8"))
    if check_only and stale:
        print(
            "coney-tools: out of date with research/pcsx2-recipes.toml (`coney-tools pcsx2 recipe render`):",
            file=sys.stderr,
        )
        for name in stale:
            print(f"  {name}", file=sys.stderr)
        return 1
    print(f"{len(stale)} page(s) {'stale' if check_only else 'written'}; {len(wanted)} in all")
    return 0
