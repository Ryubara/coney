"""The console commands reference, generated from the console's catalogs.

`coney-tools console render` writes `docs/guides/console-commands.md` from `src/console/commands.toml` (and the
developer set's file once it exists), laid out as the script bindings reference is
(docs/references/bindings/camera.md): a table of every command, then an entry per command with its syntax, its
arguments, its access level and scope, what it needs and waits for, and at least one example line with its output.
The catalog holds the examples, so the page has one source; `--check` fails when the page is stale or a command has
no example (docs/guides/console.md#catalog).
"""

from __future__ import annotations

import textwrap
from pathlib import Path

from coney_tools.console_catalog import Catalog, Command

PAGE = Path("docs/guides/console-commands.md")
WIDTH = 120  # the docs' line length (.markdownlint.yaml, MD013)
GENERATED = "<!-- Generated by `coney-tools console render` from the console's catalogs. Do not edit. -->"

_NEED_WORDS = {"game": "a game in play", "profile": "an active profile", "level": "a level in play", "disc": "a disc"}

_INTRO = (
    "Every built-in command of the [Coney console](console.md): the terminal F8 will open in the game. The page is "
    "generated from `src/console/commands.toml` (the player set, in every build, the release build included) by "
    "`coney-tools console render`; edit that file, never this page. The console's core is built; its front end and "
    "the commands' handlers are planned, and a command whose handler is not registered is unknown when typed "
    "([What is built](console.md#built)). The set is the design's proposal, which a maintainer confirms "
    "([The release set](studio/console.md#release-set))."
)
_HOW = (
    "How to read an entry: the syntax line names each argument, `<required>` or `[optional]`; the **scope** says "
    "whose game it touches (**local**: this machine's; **session**: the game everyone in a network session plays, "
    "which only the host may change), and whether it **runs at once** or **waits for the step boundary** (between two "
    "simulation steps, in the order lines were entered); **needs** is what must exist for it to run; **waits for** "
    "names the Coney feature without which the command is absent. Each example shows a line as typed (after `>`) and "
    "the lines it prints."
)


def _wrap(text: str) -> list[str]:
    """One paragraph filled to WIDTH, never breaking a word."""
    return textwrap.wrap(text, WIDTH, break_long_words=False, break_on_hyphens=False)


def _cell(text: str) -> str:
    """`text` safe in a table cell."""
    return text.replace("|", "\\|")


def _when(command: Command) -> str:
    """When the command runs."""
    return "waits for the step boundary" if command.queued else "runs at once"


def _entry(command: Command) -> list[str]:
    """One command's section."""
    lines = [f"## {command.name} {{#{command.name}}}", "", "```text", command.usage, "```", ""]
    lines += _wrap(command.summary)
    lines.append("")
    if command.args:
        lines += ["| # | Argument | Type | Default | Meaning |", "| --- | --- | --- | --- | --- |"]
        for number, arg in enumerate(command.args, start=1):
            kind = arg.type
            if arg.choices:
                kind += ": " + ", ".join(f"`{choice}`" for choice in arg.choices)
            default = f"`{arg.default}`" if arg.default else ("none (optional)" if arg.optional else "required")
            lines.append(f"| {number} | `{arg.name}` | {_cell(kind)} | {default} | {_cell(arg.help)} |")
        lines.append("")
    facts = [f"- **Access:** {command.access}; **scope:** {command.scope}, {_when(command)}"]
    if command.needs:
        facts.append("- **Needs:** " + ", ".join(_NEED_WORDS[need] for need in command.needs))
    if command.available:
        facts.append(f"- **Waits for:** the Coney feature `{command.available}`; absent until it is built")
    if command.doubles:
        facts.append(f"- **Doubles:** {command.doubles}")
    for fact in facts:
        lines += textwrap.wrap(fact, WIDTH, subsequent_indent="  ", break_long_words=False, break_on_hyphens=False)
    lines.append("")
    for example in command.examples:
        lines += ["```text", f"> {example.line}", *example.output, "```", ""]
        if not example.output:
            lines += ["It prints nothing.", ""]
    return lines


def page(catalogs: list[Catalog]) -> str:
    """The whole reference page for `catalogs` (the player set first)."""
    commands = [command for catalog in catalogs for command in catalog.commands]
    lines = ["# Console commands", "", GENERATED, ""]
    lines += [*_wrap(_INTRO), "", *_wrap(_HOW), ""]
    lines.append(f"{len(commands)} commands.")
    lines += ["", "| Command | Group | Access | Scope | Does |", "| --- | --- | --- | --- | --- |"]
    for command in commands:
        lines.append(
            f"| [`{command.name}`](#{command.name}) | {_cell(command.group)} | {command.access} | {command.scope} |"
            f" {_cell(command.summary)} |"
        )
    lines.append("")
    for command in commands:
        lines += _entry(command)
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"
