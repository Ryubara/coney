"""The C++ table of the console's player commands, generated from `src/console/commands.toml`.

`coney-tools console render-cpp` writes `src/console/commands_table.cpp`: every command's specification (name, group,
access level, scope, whether it changes something, summary, needs, the feature it waits for and its arguments) for
`coney::console::playerCatalog()` (src/console/catalog.h), as `bindings render-cpp` writes the natives' signatures.
The examples stay in the reference page; the handlers are bound by name in C++ (docs/guides/console.md#catalog).
"""

from __future__ import annotations

import re
from pathlib import Path

from coney_tools.console_catalog import PLAYER_FILE, Arg, Catalog, Command

CPP_FILE = Path("src/console/commands_table.cpp")

_TYPES = {
    "int": "Int",
    "number": "Number",
    "bool": "Bool",
    "text": "Text",
    "choice": "Choice",
    "mission": "Mission",
    "checkpoint": "Checkpoint",
    "level": "Level",
    "mod": "Mod",
    "setting": "Setting",
    "command": "Command",
}
_NEEDS = {"game": "Game", "profile": "Profile", "level": "Level", "disc": "Disc"}


def _literal(text: str) -> str:
    """`text` as a C++ string literal."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _ident(name: str) -> str:
    """A command's or argument's name as part of a C++ identifier (`load-checkpoint` -> `load_checkpoint`)."""
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def _bool(value: bool) -> str:
    """A C++ bool literal."""
    return "true" if value else "false"


def _needs(command: Command) -> str:
    """The Needs value: `0`, or the bits ORed."""
    if not command.needs:
        return "0"
    bits = " | ".join(f"needBit(Need::{_NEEDS[need]})" for need in command.needs)
    return f"static_cast<Needs>({bits})"


def _choices_name(command: Command, arg: Arg) -> str:
    """The name of a choice argument's array."""
    return f"kChoices_{_ident(command.name)}_{_ident(arg.name)}"


def _args_name(command: Command) -> str:
    """The name of a command's argument array."""
    return f"kArgs_{_ident(command.name)}"


def render_cpp(catalog: Catalog) -> str:
    """The whole generated source for the player catalog: one choices array per choice argument, one argument array
    per command with arguments, then the table, in the file's order."""
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        f"// Generated by `uv run --project python coney-tools console render-cpp` from {PLAYER_FILE.as_posix()}."
        " Do not edit.",
        "// @coney-only the Coney console's player commands (docs/guides/console.md#catalog).",
        '#include "console/catalog.h"',
        "",
        "#include <array>",
        "#include <span>",
        "#include <string_view>",
        "",
        '#include "console/command_spec.h"',
        "",
        "namespace coney::console {",
        "",
        "namespace {",
        "",
        "// Short names keep the generated lines short.",
        "using A = ArgType;",
        "",
        "// clang-format off",
    ]
    for command in catalog.commands:
        for arg in command.args:
            if arg.type == "choice":
                cells = ", ".join(_literal(choice) for choice in arg.choices)
                array = f"std::array<std::string_view, {len(arg.choices)}>"
                lines.append(f"constexpr {array} {_choices_name(command, arg)}{{{cells}}};")
        if command.args:
            lines.append(f"constexpr std::array<ArgSpec, {len(command.args)}> {_args_name(command)}{{{{")
            for arg in command.args:
                choices = _choices_name(command, arg) if arg.type == "choice" else "{}"
                lines.append(
                    f"    {{{_literal(arg.name)}, A::{_TYPES[arg.type]}, {_literal(arg.help)}, {_bool(arg.optional)},"
                    f" {_literal(arg.default)}, {choices}}},"
                )
            lines.append("}};")
    lines.append(f"constexpr std::array<CommandSpec, {len(catalog.commands)}> kCommands{{{{")
    for command in catalog.commands:
        access = "Access::Player" if command.access == "player" else "Access::Developer"
        scope = "Scope::Local" if command.scope == "local" else "Scope::Session"
        args = _args_name(command) if command.args else "{}"
        lines.append(
            f"    {{{_literal(command.name)}, {_literal(command.group)}, {access}, {scope}, {_bool(command.changes)},"
        )
        lines.append(f"     {_literal(command.summary)}, {_needs(command)}, {_literal(command.available)}, {args}}},")
    lines += [
        "}};",
        "// clang-format on",
        "",
        "} // namespace",
        "",
        "std::span<const CommandSpec> playerCatalog() { return kCommands; }",
        "",
        "} // namespace coney::console",
        "",
    ]
    return "\n".join(lines)
