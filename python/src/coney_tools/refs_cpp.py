"""The C++ tables generated from the game reference lists, written by `coney-tools refs render` with the pages.

`src/scenes/scene_casts_table.cpp` holds the Cast and Props of every scene in `research/references/scenes.yaml` that
has them: the character types and object types the scripts' scene tables bind, which Coney's scene preview (`--scene`)
plays a scene with (`coney::scenes::scriptedSceneCasts()`, src/scenes/scene_casts.h).

Research: docs/research/scenes.md#cast
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from coney_tools import refs

SCENE_CASTS_FILE = Path("src/scenes/scene_casts_table.cpp")
SCENES_YAML = Path("research/references/scenes.yaml")

# A cast or prop entry the table keeps as it is: a model or type name, `a|b`, `player`, `-` or `?`.
_ENTRY = re.compile(r"^(?:[A-Za-z0-9_]+(?:\|[A-Za-z0-9_]+)*|-|\?)$")


def _entry(value: Any) -> str:
    """One cast or prop entry as the C++ table writes it: anything that is not a name (a door's leaf, written
    `door (left leaf)`) is `?`, a binding the preview cannot make."""
    text = str(value)
    return text if _ENTRY.match(text) else "?"


def _literal(text: str) -> str:
    """`text` as a C++ string literal (the entries hold no quote or backslash)."""
    return f'"{text}"'


def scene_casts_cpp(scenes: refs.RefList) -> str:
    """The whole generated source of the scene preview's table, the scenes with a Cast or Props in list order."""
    rows = [entry for entry in scenes.entries if entry.get("kind") == "scene" and ("cast" in entry or "props" in entry)]
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        f"// Generated by `uv run --project python coney-tools refs render` from {SCENES_YAML.as_posix()}."
        " Do not edit.",
        "// @coney-only the `--scene` preview's cast (docs/research/scenes.md#cast).",
        '#include "scenes/scene_casts.h"',
        "",
        "#include <array>",
        "",
        "namespace coney::scenes {",
        "",
        "namespace {",
        "",
        "// The scene, its Cast and its Props, an entry per role or slot, separated by spaces.",
        "// clang-format off",
        f"constexpr std::array<ScriptedSceneCast, {len(rows)}> kCasts{{{{",
    ]
    for entry in rows:
        cast = " ".join(_entry(value) for value in entry.get("cast") or [])
        props = " ".join(_entry(value) for value in entry.get("props") or [])
        lines.append(f"    {{{_literal(str(entry['name']))},")
        lines.append(f"     {_literal(cast)},")
        lines.append(f"     {_literal(props)}}},")
    lines += [
        "}};",
        "// clang-format on",
        "",
        "} // namespace",
        "",
        "std::span<const ScriptedSceneCast> scriptedSceneCasts() { return kCasts; }",
        "",
        "} // namespace coney::scenes",
        "",
    ]
    return "\n".join(lines)


def files(root: Path, lists: list[refs.RefList]) -> dict[Path, str]:
    """Every generated C++ file by path, from the loaded lists (none when the scenes list is not among them)."""
    for reflist in lists:
        if reflist.topic.key == "scenes":
            return {root / SCENE_CASTS_FILE: scene_casts_cpp(reflist)}
    return {}
