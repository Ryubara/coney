"""Rendering the function database into a list page per system, `research/<system>/functions.md`.

The pages are for people; the TOML files in research/functions/ are for tools. Nothing generated is committed: the docs
build writes the pages (mkdocs_hooks.py) and `coney-tools research render OUT_DIR` writes them to a folder to look at,
like the progress tables. The page lists every researched function of the system in address order, each linked to the
section of the research page that describes it; a column appears only when some entry uses it.

Research: docs/guides/research-function-database.md
"""

from __future__ import annotations

from pathlib import Path

from coney_tools import research_links
from coney_tools.research_functions import FUNCTIONS_DIR, LEVELS, NO_LEVEL, Entry, Gap, SystemFunctions

RESEARCH_DIR = Path("docs/research")


def _cell(text: str) -> str:
    """Text safe inside a table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def _rebased(text: str, system: str) -> str:
    """A role or note written relative to docs/research, as it reads from the system's folder."""
    return research_links.rebase_links(text, "", system, "")


def _link(target: str, system: str) -> str:
    """A link to `page.md#section` (relative to docs/research) from the system's folder, labelled with the target."""
    return f"[{target}]({research_links.rebase_target(target, '', system, '')})"


def _summary(entries: tuple[Entry, ...]) -> str:
    """`12 functions: 9 confirmed (code), 3 inferred.`"""
    counts = [(label, sum(1 for e in entries if e.level == key)) for key, label in LEVELS.items()]
    counts.append((f"with {NO_LEVEL}", sum(1 for e in entries if not e.level)))
    parts = ", ".join(f"{count} {label}" for label, count in counts if count)
    noun = "function" if len(entries) == 1 else "functions"
    return f"{len(entries)} {noun}: {parts}." if parts else f"{len(entries)} {noun}."


def _level_cell(entry: Entry, system: str) -> str:
    """The level's label, with the entry's note after it when it has one; a note that already starts with the label
    (an imported mixed cell, `confirmed (code); the rock inferred`) stands alone, so the label is not doubled. Links in
    the note are written relative to docs/research, like the role's, and read from the system's folder."""
    label = LEVELS.get(entry.level, NO_LEVEL)
    if not entry.note:
        return label
    note = _rebased(entry.note, system)
    return _cell(note if note.lower().startswith(label) else f"{label}; {note}")


def _coney_cell(entry: Entry) -> str:
    """Where the port lives and how far it has been checked."""
    if not entry.coney:
        return ""
    return f"`{entry.coney}` ({entry.status})" if entry.status else f"`{entry.coney}`"


def _gap_tracker(gap: Gap, system: str) -> str:
    """What tracks a gap: its issue number and its open question."""
    parts = []
    if gap.issue is not None:
        parts.append(f"#{gap.issue}")
    if gap.question:
        parts.append(_link(gap.question, system))
    return ", ".join(parts)


def render_system(system: SystemFunctions, system_page: str | None) -> str:
    """The list page of one system as Markdown; `system_page` is the link from it to the system's own page, if any."""
    name = system.system
    source = (FUNCTIONS_DIR / f"{name}.toml").as_posix()
    entries = tuple(sorted(system.entries, key=lambda e: e.address))
    levels = "../../guides/research-evidence.md#evidence-levels"
    out = [
        f"<!-- Generated by `coney-tools research render` from {source}. Do not edit. -->",
        "",
        f"# Function list: {name}",
        "",
        f"{_summary(entries)} Every row is one function of the original, by address, with the name it has in the",
        f"shared Ghidra project, how we know what it does ([evidence levels]({levels})) and the section that",
        "describes it.",
        "",
    ]
    if system_page:
        out += [f"How these work together is on [the {name} page]({system_page}).", ""]
    out += [
        f"This page is made from [{source}](repo:{source}); fix a row there",
        "([the function database](../../guides/research-function-database.md)).",
        "",
    ]
    has_kind = any(e.kind for e in entries)
    has_coney = any(e.coney for e in entries)
    header = ["Address", "Name", *(["Kind"] if has_kind else []), "Role", "Level", "Section"]
    header += ["In Coney"] if has_coney else []
    out += ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    for entry in entries:
        cells = [f'<span id="0x{entry.address:08x}"></span>`0x{entry.address:08x}`', f"`{entry.name}`"]
        if has_kind:
            cells.append(_cell(entry.kind))
        cells += [_cell(_rebased(entry.role, name)), _level_cell(entry, name), _link(entry.page, name)]
        if has_coney:
            cells.append(_coney_cell(entry))
        out.append("| " + " | ".join(cells) + " |")
    gapped = [(e, g) for e in entries for g in e.gaps]
    if gapped:
        out += [
            "",
            "## Stand-ins and pieces not ported {#gaps}",
            "",
            "A stand-in is a piece Coney does differently on purpose; the question or issue says why and what would "
            "replace it. A piece not ported waits for the issue.",
            "",
            "| Function | Relation | What | Tracked by |",
            "| --- | --- | --- | --- |",
        ]
        out += [f"| `{e.name}` | {g.relation} | {_cell(g.what)} | {_gap_tracker(g, name)} |" for e, g in gapped]
    return "\n".join(out) + "\n"


def _system_page_link(root: Path, system: str) -> str | None:
    """The link from `<system>/functions.md` to the system's hand-written page, or None while it has none."""
    base = root / RESEARCH_DIR
    if (base / system / "index.md").is_file():
        return "index.md"
    if (base / f"{system}.md").is_file():
        return f"../{system}.md"
    return None


def render_pages(root: Path, systems: list[SystemFunctions]) -> dict[str, str]:
    """Every list page, by its path below docs/ (`research/<system>/functions.md`)."""
    return {f"research/{s.system}/functions.md": render_system(s, _system_page_link(root, s.system)) for s in systems}
