"""Tests for the generated function list pages (coney_tools.research_render), on made-up systems."""

from __future__ import annotations

from pathlib import Path

from coney_tools import research_functions as rf
from coney_tools import research_render


def system_of(*entries: rf.Entry, name: str = "combat") -> rf.SystemFunctions:
    """A system with `entries`."""
    return rf.SystemFunctions(name, Path(f"research/functions/{name}.toml"), "", entries)


MINIMAL = system_of(
    rf.Entry(0x100200, "Grab_Start", "combat/grabs.md#grab", "confirmed-code", role="plays the grab intro"),
    rf.Entry(0x100300, "Grab_Skip", "combat.md", "inferred", role="a | pipe, and [a link](grabs.md#x)"),
)


def test_the_page_is_a_title_a_summary_and_a_table() -> None:
    """The simplest page: what it is, how many functions and at which levels, then one row per function."""
    page = research_render.render_system(MINIMAL, "../combat.md")
    lines = page.splitlines()
    assert lines[0].startswith("<!-- Generated by `coney-tools research render` from research/functions/combat.toml")
    assert "# Function list: combat" in lines
    assert "2 functions: 1 confirmed (code), 1 inferred." in page
    assert "[the combat page](../combat.md)" in page
    assert "[research/functions/combat.toml](repo:research/functions/combat.toml)" in page
    assert "| Address | Name | Role | Level | Section |" in lines
    assert (
        '| <span id="0x00100200"></span>`0x00100200` | `Grab_Start` | plays the grab intro | confirmed (code) | '
        "[combat/grabs.md#grab](grabs.md#grab) |"
    ) in lines


def test_a_role_is_a_cell_whose_links_are_rebased_and_pipes_escaped() -> None:
    """A role link is relative to docs/research, so it gains a folder up; a pipe cannot end the cell."""
    page = research_render.render_system(MINIMAL, None)
    assert "a \\| pipe, and [a link](../grabs.md#x)" in page


def test_without_a_system_page_there_is_no_link_to_it() -> None:
    """Before a system has a page of its own, the list does not invent a link."""
    assert "the combat page" not in research_render.render_system(MINIMAL, None)


def test_kind_and_coney_columns_appear_only_when_used() -> None:
    """A column no entry uses would be a column of dashes."""
    plain = research_render.render_system(MINIMAL, None)
    assert "| Kind |" not in plain
    assert "In Coney" not in plain
    rich = system_of(
        rf.Entry(0x100200, "Grab_Start", "combat.md", "confirmed-code", kind="start", role="r", note="the id inferred"),
        rf.Entry(
            0x100300,
            "Grab_End",
            "combat.md",
            "confirmed-code",
            role="r",
            coney="src/core/combat/grab.cpp:Grab::end",
            status="compared",
        ),
    )
    page = research_render.render_system(rich, None)
    assert "| Address | Name | Kind | Role | Level | Section | In Coney |" in page
    assert "| confirmed (code); the id inferred |" in page
    assert "`src/core/combat/grab.cpp:Grab::end` (compared)" in page


def test_gaps_get_their_own_table() -> None:
    """Stand-ins and unported pieces are listed with what tracks them."""
    entry = rf.Entry(
        0x100200,
        "Grab_Start",
        "combat.md",
        "confirmed-code",
        gaps=(
            rf.Gap("fixed counter chance", "stand-in", None, "combat/grabs.md#q-counter"),
            rf.Gap("the mount strikes", "not-ported", 123),
        ),
    )
    page = research_render.render_system(system_of(entry), None)
    assert "## Stand-ins and pieces not ported {#gaps}" in page
    assert (
        "| `Grab_Start` | stand-in | fixed counter chance | [combat/grabs.md#q-counter](grabs.md#q-counter) |" in page
    )
    assert "| `Grab_Start` | not-ported | the mount strikes | #123 |" in page
    assert "#gaps" not in research_render.render_system(MINIMAL, None)


def test_a_note_that_starts_with_the_level_is_not_doubled() -> None:
    """An imported mixed cell keeps its text as the note; the Level cell shows that text once, not the label twice."""
    entry = rf.Entry(0x100200, "Car_Hit", "cars.md", "confirmed-code", role="r", note="confirmed (code); rock inferred")
    page = research_render.render_system(system_of(entry), None)
    assert "confirmed (code); rock inferred" in page
    assert "confirmed (code); confirmed (code)" not in page


def test_an_empty_role_and_a_not_needed_entry() -> None:
    """A function with no role shows an empty cell; a not-needed one shows its reason as the role."""
    page = research_render.render_system(
        system_of(
            rf.Entry(0x100200, "A", "combat.md", "inferred"),
            rf.Entry(0x100300, "B", "combat.md", "not-needed", role="debug stub"),
        ),
        None,
    )
    assert "| `A` |  | inferred |" in page
    assert "| `B` | debug stub | not needed |" in page


def test_render_pages_writes_one_page_per_system_below_research(tmp_path: Path) -> None:
    """The pages are keyed by their path below docs/, and link to the system's page when it exists."""
    (tmp_path / "docs" / "research").mkdir(parents=True)
    (tmp_path / "docs" / "research" / "combat.md").write_text("# Combat\n", encoding="utf-8")
    (tmp_path / "docs" / "research" / "ai").mkdir()
    (tmp_path / "docs" / "research" / "ai" / "index.md").write_text("# AI\n", encoding="utf-8")
    pages = research_render.render_pages(
        tmp_path, [MINIMAL, system_of(rf.Entry(0x100400, "X", "ai/index.md", "inferred"), name="ai")]
    )
    assert sorted(pages) == ["research/ai/functions.md", "research/combat/functions.md"]
    assert "[the combat page](../combat.md)" in pages["research/combat/functions.md"]
    assert "[the ai page](index.md)" in pages["research/ai/functions.md"]


def test_rendering_is_deterministic() -> None:
    """The same data gives the same text, whatever the order the entries were built in."""
    shuffled = system_of(*reversed(MINIMAL.entries))
    assert research_render.render_system(shuffled, None) == research_render.render_system(MINIMAL, None)
